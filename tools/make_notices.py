"""Regenerates THIRD-PARTY-NOTICES.txt from the license files vcpkg installs next to the libraries.

Run after the dependencies changed (new library or new version), from the project folder:

    python tools/make_notices.py

It needs a finished build (build/vcpkg_installed/...) and the vcpkg build trees (C:/vcpkg/buildtrees) for PCRE2's licence.
Check that the component list below still matches the DLLs in build/package/Full.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHARE = ROOT / "build" / "vcpkg_installed" / "x64-windows" / "share"
VCPKG_BUILDTREES = pathlib.Path("C:/vcpkg/buildtrees")
BAR = "=" * 78


def read(path):
    return pathlib.Path(path).read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip("\n")


def port_version(port):
    """Version of a vcpkg port, read from its installed status/spdx data; falls back to the ports folder."""
    manifest = pathlib.Path("C:/vcpkg/ports") / port / "vcpkg.json"
    if manifest.exists():
        m = re.search(r'"version(?:-string|-semver|-date)?"\s*:\s*"([^"]+)"', manifest.read_text(encoding="utf-8"))
        if m:
            return m.group(1)
    return "unknown"


def section(title, intro, license_text):
    return f"{BAR}\n{title}\n{BAR}\n\n{intro.strip()}\n\n----- license text -----\n\n{license_text}\n"


def main():
    pcre_licence = next(VCPKG_BUILDTREES.glob("pcre2/src/*/LICENCE.md"), None)
    if pcre_licence is None:
        sys.exit("PCRE2 licence not found in C:/vcpkg/buildtrees/pcre2/src/*/LICENCE.md")

    qt_version = port_version("qtbase")
    occt_version = port_version("opencascade")

    parts = [
        "CADscout - third-party notices\n"
        "==============================\n\n"
        "CADscout itself is free software under the MIT license (see the file LICENSE).\n"
        "It is built with, and its program folder contains, the open-source software listed below.\n"
        "Each component is used under the license named in its section; the full license texts follow.\n"
        "This file is generated by tools/make_notices.py.\n",
        section(
            f"Qt {qt_version} (Qt Core, Gui, Widgets, OpenGL, OpenGL Widgets, SVG)",
            f"""CADscout uses the Qt toolkit, version {qt_version}, under the GNU Lesser General Public License
version 3 (LGPL-3.0). Copyright (C) The Qt Company Ltd. and other contributors. Qt and the Qt logo are
trademarks of The Qt Company Ltd.

The Qt libraries are separate files in the program folder (Qt6Core.dll, Qt6Gui.dll, Qt6Widgets.dll,
Qt6OpenGL.dll, Qt6OpenGLWidgets.dll, Qt6Svg.dll and the platforms folder). They are not modified by CADscout
and can be replaced by your own build of the same Qt version.
The Qt source code is available from https://download.qt.io/official_releases/qt/ and https://www.qt.io/ .
The complete license texts of Qt and of the third-party code bundled in it (from the build system) follow.""",
            "[qtbase]\n\n" + read(SHARE / "qtbase" / "copyright") + "\n\n[qtsvg]\n\n" + read(SHARE / "qtsvg" / "copyright"),
        ),
        section(
            f"Open CASCADE Technology (OCCT) {occt_version}",
            f"""CADscout uses Open CASCADE Technology {occt_version} to read STEP, IGES, BREP, STL, OBJ, PLY, VRML and
glTF files and to build the 3D model. Copyright (C) Open CASCADE SAS and contributors.

This software makes use of, or is based on, facilities provided by the Open CASCADE Technology software.
OCCT is licensed under the GNU Lesser General Public License version 2.1 with the Open CASCADE exception
(version 1.0). The libraries are separate files in the program folder (TK*.dll) and are not modified by CADscout.
Source code: https://github.com/Open-Cascade-SAS/OCCT and https://dev.opencascade.org/ .""",
            read(SHARE / "opencascade" / "copyright"),
        ),
        section(
            "Tabler Icons",
            "The toolbar icons are from Tabler Icons (https://tabler.io/icons), MIT license.",
            read(ROOT / "resources" / "icons" / "LICENSE-tabler.txt"),
        ),
        section(
            "zlib",
            "zlib is used to read the compressed parts of 3MF files (z.dll) and by Qt.",
            read(SHARE / "zlib" / "copyright"),
        ),
        section(
            "RapidJSON",
            "RapidJSON is compiled into Open CASCADE's glTF reader (header-only library).",
            read(SHARE / "rapidjson" / "copyright"),
        ),
        section(
            "double-conversion",
            "double-conversion is used by Qt (double-conversion.dll).",
            read(SHARE / "double-conversion" / "copyright"),
        ),
        section(
            "md4c",
            "md4c is used by Qt (md4c.dll).",
            read(SHARE / "md4c" / "copyright"),
        ),
        section(
            "PCRE2",
            "PCRE2 is used by Qt (pcre2-16.dll).",
            read(pcre_licence),
        ),
    ]
    out = ROOT / "THIRD-PARTY-NOTICES.txt"
    out.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {out} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
